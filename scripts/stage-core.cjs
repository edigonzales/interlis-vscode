const fs=require('node:fs');
const path=require('node:path');
const cp=require('node:child_process');
const crypto=require('node:crypto');
const args=process.argv.slice(2);
if(args.length!==2 || args[0]!=='--core-dir' || !path.isAbsolute(args[1])) throw new Error('Usage: stage:core -- --core-dir <absolute checkout>');
const core=fs.realpathSync(args[1]);
const sha=cp.execFileSync('git',['rev-parse','HEAD'],{cwd:core,encoding:'utf8'}).trim();
if(cp.execFileSync('git',['status','--porcelain','--untracked-files=no'],{cwd:core,encoding:'utf8'}).trim()) throw new Error('Core tracked tree must be clean');
cp.execFileSync(path.join(core,'gradlew'),[':interlis-lsp:installDist','--no-daemon'],{cwd:core,stdio:'inherit'});
const lib=path.join(core,'interlis-lsp/build/install/interlis-lsp/lib');
const names=fs.readdirSync(lib).sort();
if(!names.length || names.some(x=>!x.endsWith('.jar'))) throw new Error('Invalid server distribution');
fs.rmSync('artifacts/server',{recursive:true,force:true});fs.mkdirSync('artifacts/server/lib',{recursive:true});
const files=names.map(name=>{const bytes=fs.readFileSync(path.join(lib,name));fs.writeFileSync(path.join('artifacts/server/lib',name),bytes);return {path:'lib/'+name,sha256:crypto.createHash('sha256').update(bytes).digest('hex')};});
fs.mkdirSync('release',{recursive:true});
fs.writeFileSync('release/editor-artifacts.lock.json',JSON.stringify({schemaVersion:1,coreCommit:sha,protocolVersion:'lsp-3.17-baseline',mainClass:'guru.interlis.lsp.Main',serverVersion:'0.2.0-SNAPSHOT',files},null,2)+'\n');
fs.copyFileSync(path.join(core,'LICENSE'),'licenses/interlis-java.txt');
if(cp.execFileSync('git',['rev-parse','HEAD'],{cwd:core,encoding:'utf8'}).trim()!==sha) throw new Error('Core HEAD changed while staging');
console.log(`Staged ${files.length} libraries from ${sha}`);
